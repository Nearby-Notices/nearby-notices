"""Nearby Notices as an MCP server, so an AI agent can ask "what public notices are there near X?" and "read notice N".

Same index, same rules as the website: only notices published by public bodies, never notices about people; every
plain-English sentence checked against the notice; the verbatim text and the Gazette link always returned so the
agent can cite the record. Runs over stdio:  uv run python -m nearby_notices.mcp_server
"""
from __future__ import annotations

import re
import time

from mcp.server.mcpserver import MCPServer

from . import config, geo, groups, search, worker
from .categories import ALLOWED, EXCLUDED

_ID = re.compile(r"^\d{1,12}$")
READ_TIMEOUT_S = 120

INSTRUCTIONS = (
    "Public notices from The Gazette (UK) near a postcode or town, read in plain English. Covers only notices "
    "published by public bodies and companies acting as authorities: roads and transport, planning, environment, "
    "water, forestry, electricity. It never returns notices about individuals (insolvency, estates, appointments) and "
    "is not for finding out about people. The plain-English text is generated by a language model and checked "
    "sentence by sentence against the notice; it can still be wrong, so quote the notice's own words for anything "
    "that matters and give the Gazette link. This server does not give legal advice. Notice data is reused under "
    "the Open Government Licence v3."
)

server = MCPServer(name="nearby-notices", title="Nearby Notices", instructions=INSTRUCTIONS, version="0.1.0")


def _summary(r: dict) -> dict:
    x = r["x"] or {}
    return {
        "notice_id": r["n"]["id"],
        "kind": groups.group_name(r["group"]),
        "category": r["n"]["category"],
        "published": r["n"]["published"],
        "title": x.get("what") or r["n"]["title"],
        "distance": r["dist"],
        "filed_postcode": (r["near"] or {}).get("postcode"),
        "plain_english_ready": r["x"] is not None and not x.get("error"),
        "url": r["n"]["url"],
    }


def find_notices_near(place: str, distance: float = 3, unit: str = "mi") -> dict:
    """Find public notices near a UK postcode or town. `place` is a postcode (for example "DY1 1HF") or a town
    ("Dudley"). `distance` is snapped to the offered choices: miles 1, 3, 5, 10, 15 or kilometres 2, 5, 10, 15, 25;
    `unit` is "mi" or "km". Returns up to 12 notices, newest first, each with its id, kind, date, a one-line title,
    how far the nearest postcode it is filed under is from the place, whether a plain-English version is ready, and
    the Gazette link. Call read_notice with an id for the full text and the plain-English version."""
    unit = geo.unit_key(unit)
    found = search.find(place, distance, unit)
    if not found:
        return {"error": "place not found; give a full UK postcode or a town name", "notices": []}
    if found.pending:
        worker.enqueue(found.pending)   # start reading in the background so read_notice is quick
    return {
        "place": found.where.name,
        "postcode": found.where.postcode,
        "within": geo.fmt(found.asked_m, unit),
        "count": len(found.results),
        "notices": [_summary(r) for r in found.results],
        "note": "Pins and distances refer to the postcodes each notice is filed under, which for a council order is often "
                "the council's address; the notice text names the places affected.",
    }


def read_notice(notice_id: str) -> dict:
    """Read one notice by id (from find_notices_near): the notice as published, word for word, and a plain-English
    version: what is changing, the places affected, the authority, from when and until when, the kind of notice,
    the notice's own sentence on how to object (quoted, never composed), and a short summary in which every sentence
    was checked against the notice; sentences that failed the check were removed and are counted. If the version is
    not ready it is made now, which can take a minute. Always cite the url."""
    if not _ID.match(notice_id or ""):
        return {"error": "notice_id must be the numeric id from find_notices_near"}
    t0 = time.time()
    while worker.is_pending(notice_id) and time.time() - t0 < READ_TIMEOUT_S:
        time.sleep(0.5)
    got = search.read(notice_id, make_now=True)
    if not got:
        return {"error": "unknown notice id; this server only holds notices returned by find_notices_near, in the covered categories"}
    row, x = got
    x = x or {}
    out = {
        "notice_id": row["id"],
        "kind": groups.group_name(groups.group_of(row["notice_code"])),
        "category": row["category"],
        "published": row["published"],
        "url": row["url"],
        "as_published": row["text"],
        "plain_english": None if x.get("error") else {
            "what": x.get("what"), "places": x.get("places", []), "authority": x.get("authority"),
            "starts": x.get("starts"), "ends": x.get("ends"), "kind_of_notice": x.get("kind"),
            "how_to_object_quoted": x.get("objection"), "summary": x.get("summary", []),
            "sentences_removed_by_check": len(x.get("removed", [])), "of_which_for_giving_advice": x.get("advice_removed", 0),
            "place_names_dropped_by_check": x.get("dropped_places", []), "model_values_dropped_by_check": x.get("dropped_fields", []),
            "sentences_in_notice_addressed_to_a_model_ignored": x.get("scrubbed", 0),
        },
        "plain_english_error": x.get("error"),
        "caution": "The plain-English version is generated and checked, not official. The text under as_published is the record.",
    }
    return out


def coverage() -> dict:
    """What this server covers and refuses, and the data licence and privacy terms. Call this before answering
    questions about what kinds of notice can be found here."""
    return {
        "covered": list(ALLOWED.values()),
        "refused_by_design": list(EXCLUDED.values()),
        "why_refused": "The Gazette's licence does not cover personal data and this tool is not for finding out about people.",
        "licence": "Notice data: The Gazette, Open Government Licence v3. Place lookup: postcodes.io, Open Government Licence.",
        "privacy": "No accounts, no cookies. What you ask is used for the search and not stored.",
        "model": config.MODEL,
        "distances": {u: spec["choices"] for u, spec in geo.UNITS.items()},
    }


for fn in (find_notices_near, read_notice, coverage):
    server.tool()(fn)


def main() -> None:
    worker.start()
    server.run(transport="stdio")


if __name__ == "__main__":
    main()
